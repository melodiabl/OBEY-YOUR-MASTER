const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { chromium } = require(process.env.OBEY_BROWSER_PLAYWRIGHT_MODULE || process.argv[3] || 'playwright')
const origin = process.argv[2] || ''
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(origin)) throw new Error('Use the isolated loopback configuration fixture')
;(async () => {
  const probe = await fetch(origin + '/fixture-record').then(response => response.json())
  assert.equal(probe.fixture, true)
  assert.equal(probe.record.guildId, 'configuration-fixture')
  const directory = path.resolve(__dirname, '../docs/platform/evidence/configuration')
  await fs.mkdir(directory, { recursive: true })
  const browser = await chromium.launch({ headless: true })
  const errors = []
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    await context.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.fulfill({ body: '', contentType: 'text/css' }))
    const page = await context.newPage()
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(origin + '/fixture-login')
    await page.locator('#config-fields').waitFor({ state: 'visible' })
    await page.waitForFunction(() => !document.getElementById('config-fields').disabled)
    const csrfDenied = await context.request.put(origin + '/api/guilds/configuration-fixture/modules/welcome/draft', { data: { config: { channelId: null, message: 'forged' }, expectedDraftRevision: 0, expectedPublishedRevision: '0'.repeat(64) } })
    assert.equal(csrfDenied.status(), 403)
    await page.locator('#config-message').fill('Hola {username} en {guild}. <img src=x onerror=alert(1)>')
    await page.locator('#config-preview').click()
    await page.locator('#config-preview-panel').waitFor({ state: 'visible' })
    assert.match(await page.locator('#config-preview-content').textContent(), /Hola Miembro de ejemplo en Servidor de ejemplo/)
    assert.equal(await page.locator('#config-preview-content img').count(), 0)
    await page.locator('#config-save').click()
    await page.waitForFunction(() => document.getElementById('config-status').textContent.startsWith('Borrador guardado'))
    const persisted = await fetch(origin + '/fixture-record').then(response => response.json())
    assert.match(persisted.record.welcome.msg, /^Bienvenido/)
    await page.reload()
    await page.waitForFunction(() => !document.getElementById('config-publish').disabled)
    assert.match(await page.locator('#config-message').inputValue(), /^Hola/)
    const second = await context.newPage()
    second.on('pageerror', error => errors.push(error.message))
    await second.goto(origin + '/configuration/configuration-fixture/welcome')
    await second.waitForFunction(() => !document.getElementById('config-fields').disabled)
    await page.locator('#config-message').fill('Mensaje aprobado para {user} · ' + 'texto largo '.repeat(25))
    await page.locator('#config-save').click()
    await page.waitForFunction(() => document.getElementById('config-status').textContent.startsWith('Borrador guardado'))
    await second.locator('#config-message').fill('Edición de la segunda pestaña')
    await second.locator('#config-save').click()
    await second.locator('#config-conflict').waitFor({ state: 'visible' })
    assert.equal(await second.locator('#config-message').inputValue(), 'Edición de la segunda pestaña')
    assert.equal(await second.locator('#config-save').isDisabled(), true)
    await second.locator('#config-refresh').click()
    await second.waitForFunction(() => !document.getElementById('config-save').disabled)
    assert.equal(await second.locator('#config-message').inputValue(), 'Edición de la segunda pestaña')
    await page.locator('#config-publish').click()
    await page.waitForFunction(() => document.getElementById('config-status').textContent.startsWith('Borrador publicado'))
    const after = await fetch(origin + '/fixture-record').then(response => response.json())
    assert.match(after.record.welcome.msg, /^Mensaje aprobado/)
    assert.equal(after.record.welcome.dm, true); assert.equal(after.record.welcome.image, true)
    assert.equal(after.record.configurationDrafts.welcome.state, 'published')
    await page.screenshot({ path: path.join(directory, 'desktop.png'), fullPage: true })
    const widths = [320, 768, 1024, 1440], overflow = []
    for (const width of widths) {
      await page.setViewportSize({ width, height: 1000 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow ${width}`)
      const bounds = await page.evaluate(() => [...document.querySelectorAll('#configuration-editor .card, #configuration-editor p, #configuration-editor pre, #config-form, #config-message, .configuration-heading')].filter(element => element.getClientRects().length).map(element => ({ element: element.id || element.className, right: element.getBoundingClientRect().right, viewport: innerWidth })))
      assert.ok(bounds.every(entry => entry.right <= entry.viewport + 1), JSON.stringify(bounds))
      overflow.push({ width, horizontalOverflow: false })
    }
    await page.setViewportSize({ width: 320, height: 1000 })
    await page.waitForFunction(() => document.getElementById('sidebar').getBoundingClientRect().right <= 1)
    await page.screenshot({ path: path.join(directory, 'mobile.png'), fullPage: true })
    await page.locator('#config-channel').focus()
    await page.keyboard.press('Tab')
    assert.equal(await page.locator('#config-message').evaluate(element => element === document.activeElement), true)
    await fetch(origin + '/fixture-mode/offline')
    await page.locator('#config-message').fill('Pendiente de guardar')
    await page.locator('#config-save').click()
    await page.waitForFunction(() => document.getElementById('config-status').textContent.includes('No se pudo confirmar'))
    assert.equal(await page.locator('#config-message').inputValue(), 'Pendiente de guardar')
    await fetch(origin + '/fixture-mode/online')
    await page.locator('#config-refresh').click()
    await page.waitForFunction(() => !document.getElementById('config-save').disabled)
    assert.equal(await page.locator('#config-message').inputValue(), 'Pendiente de guardar')
    await fetch(origin + '/fixture-mode/denied')
    await page.locator('#config-refresh').click()
    await page.waitForFunction(() => document.getElementById('config-status').textContent.includes('acceso'))
    assert.equal(await page.locator('#config-message').isDisabled(), true)
    assert.equal(await page.locator('#config-message').inputValue(), '')
    assert.equal(await page.locator('#config-published-message').textContent(), '')
    await fetch(origin + '/fixture-mode/allowed')
    assert.deepEqual(errors, [])
    const result = { fixture: true, backend: 'real Express/EJS/CSRF/domain services; in-memory Mongo adapter and fake Discord permissions',
      previewUsesSharedRenderer: true, csrfMissingRejected: true, escapedContent: true, draftDoesNotActivate: true, draftReloaded: true, twoTabConflictPreservesInput: true,
      explicitPublication: true, legacyDMPreserved: true, legacyCardsPreserved: true, keyboardNavigation: true,
      unknownWritePreservesInput: true, accessRevocationClearsData: true, breakpoints: overflow, pageErrors: errors }
    await fs.writeFile(path.join(directory, 'browser.json'), JSON.stringify(result, null, 2) + '\n')
    console.log(JSON.stringify(result))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
