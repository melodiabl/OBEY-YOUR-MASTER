const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { createCanvas } = require('@napi-rs/canvas')
const { chromium } = require(process.argv[3] || 'playwright')
const origin = process.argv[2]
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(origin || '')) throw Error('Use isolated loopback cards fixture')
async function main() {
  const info = await fetch(origin + '/fixture-info').then(response => response.json())
  assert.equal(info.fixture, true); assert.equal(info.production, false)
  assert.equal((await fetch(origin + '/fixture-reset').then(response => response.json())).fixture, true)
  const directory = path.resolve(__dirname, '../docs/platform/evidence/cards-web')
  await fs.mkdir(directory, { recursive: true })
  const browser = await chromium.launch({ headless: true }), errors = []
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    await context.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.fulfill({ body: '', contentType: 'text/css' }))
    const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message))
    await page.goto(origin + '/fixture-login')
    await page.waitForFunction(() => !document.getElementById('cards-preview-fields').disabled)
    assert.equal(await page.locator('#cards-empty').isVisible(), true)
    const canvas = createCanvas(480, 180), ctx = canvas.getContext('2d')
    const gradient = ctx.createLinearGradient(0, 0, 480, 180); gradient.addColorStop(0, '#d5a344'); gradient.addColorStop(1, '#1c4768'); ctx.fillStyle = gradient; ctx.fillRect(0, 0, 480, 180)
    const png = canvas.toBuffer('image/png'), filename = '<img onerror=evil()> fondo.png'
    await page.locator('#cards-file').setInputFiles({ name: 'invalid.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') })
    await page.locator('#cards-upload button').click(); await page.waitForFunction(() => document.getElementById('cards-status').textContent.includes('validar'))
    assert.equal(await page.locator('.cards-asset').count(), 0)
    await page.locator('#cards-file').setInputFiles({ name: filename, mimeType: 'image/png', buffer: png })
    await page.locator('#cards-upload button').click(); await page.waitForFunction(() => document.querySelectorAll('.cards-asset').length === 1)
    assert.equal(await page.locator('.cards-asset strong').textContent(), filename)
    assert.equal(await page.locator('.cards-asset img').count(), 1)
    assert.equal(await page.locator('#cards-active').textContent(), 'Fondo activo: Fondo anterior del bot')
    await page.locator('.cards-asset button').last().click(); await page.locator('#cards-delete-yes').click()
    await page.waitForFunction(() => document.querySelectorAll('.cards-asset').length === 0)
    await page.locator('#cards-file').setInputFiles({ name: 'Comunidad-dorada.png', mimeType: 'image/png', buffer: png })
    await page.locator('#cards-upload button').click(); await page.waitForFunction(() => document.querySelectorAll('.cards-asset').length === 1)
    await page.locator('.cards-asset button').first().click()
    await page.waitForFunction(() => !document.getElementById('cards-preview-image').hidden)
    assert.equal(await page.locator('#cards-preview-image').evaluate(image => image.naturalWidth), 1772)
    await page.locator('#cards-apply').click(); await page.waitForFunction(() => document.getElementById('cards-active').textContent.includes('Comunidad-dorada'))
    assert.equal(await page.locator('.cards-asset button').last().isDisabled(), true)
    await page.locator('#cards-name').fill('Nombre largo 👨‍👩‍👧‍👦 日本語 '.repeat(4))
    await page.locator('#cards-preview-form button[type=submit]').click()
    await page.waitForFunction(() => document.getElementById('cards-status').textContent.startsWith('Vista previa lista'))
    assert.ok((await page.locator('#cards-preview-text').textContent()).includes('日本語'))
    await page.locator('#cards-name').fill('María Fernández de la Comunidad')
    await page.locator('#cards-preview-form button[type=submit]').click()
    await page.waitForFunction(() => document.getElementById('cards-status').textContent.startsWith('Vista previa lista'))
    await page.screenshot({ path: path.join(directory, 'desktop.png'), fullPage: true })
    for (const width of [320, 768, 1024, 1440]) {
      await page.setViewportSize({ width, height: 1000 })
      assert.equal(await page.evaluate(() => [...document.querySelectorAll('#cards-editor .card, #cards-file, #cards-background, #cards-preview-image')].every(element => element.getBoundingClientRect().right <= innerWidth + 1)), true, 'overflow at ' + width)
    }
    await page.setViewportSize({ width: 320, height: 1000 })
    await page.waitForFunction(() => document.getElementById('sidebar').getBoundingClientRect().right <= 1)
    await page.screenshot({ path: path.join(directory, 'mobile.png'), fullPage: true })
    await page.locator('#cards-background').selectOption('neutral'); await page.locator('#cards-apply').click()
    await page.waitForFunction(() => document.getElementById('cards-active').textContent.includes('predeterminado'))
    await page.locator('.cards-asset button').last().click(); await page.locator('#cards-delete-confirm').waitFor({ state: 'visible' })
    assert.equal(await page.locator('#cards-delete-yes').evaluate(element => document.activeElement === element), true)
    await page.locator('#cards-delete-yes').click(); await page.waitForFunction(() => document.querySelectorAll('.cards-asset').length === 0)
    await fetch(origin + '/fixture-mode/denied'); await page.locator('#cards-refresh').click()
    await page.waitForFunction(() => document.getElementById('cards-status').textContent.includes('acceso'))
    assert.equal(await page.locator('#cards-preview-image').isVisible(), false)
    assert.equal(await page.locator('#cards-name').isDisabled(), true)
    assert.deepEqual(errors, [])
    const report = { fixture: true, production: false, uploadsNormalized: true, uploadDoesNotActivate: true, privateGallery: true,
      malformedRejected: true, namesRenderedAsText: true, workerPreview: true, activateAndDelete: true, activeDeletionBlocked: true,
      longUnicodeName: true, keyboardFocus: true, revocationClearsPreview: true, breakpoints: [320, 768, 1024, 1440], pageErrors: errors }
    await fs.writeFile(path.join(directory, 'browser.json'), JSON.stringify(report, null, 2) + '\n')
    console.log(JSON.stringify(report))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
